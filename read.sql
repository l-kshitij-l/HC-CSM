     CURSOR DIALER_PENDING_REQUEST
      IS
      SELECT ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DD_PARTITION_DATE, SD_TIEBREAKER
      FROM EXTERNAL_MESSAGE_DATA EMD 
      WHERE EXISTS (SELECT 1 FROM PORTFOLIOS PL 
                        WHERE PL.ACTION_LEVEL_ID IN (1,2,3,4,5,6,7)   ----generic csm
                        AND EMD.LPORTFOLIOID=PL.LID
                        AND ROWNUM=1)
