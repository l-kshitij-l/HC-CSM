-- 1a. Value domain of the two disposition columns, per channel feed (today's data)
SELECT RECORD_SOURCE_ID,
       SD_REAL_TIME_DISPOSITION,
       SD_REAL_TIME_RULE_DISPOSITION,
       SD_REAL_TIME_STATUS,
       COUNT(*) AS CNT
FROM   SHORTWINDOW
WHERE  DD_PARTITION_DATE = TRUNC(SYSDATE)
GROUP  BY RECORD_SOURCE_ID, SD_REAL_TIME_DISPOSITION,
          SD_REAL_TIME_RULE_DISPOSITION, SD_REAL_TIME_STATUS
ORDER  BY RECORD_SOURCE_ID, CNT DESC;


-- 1b. Only if 1a is all-NULL: is anything RT-processed? (per the deprecated-but-telling status flag)
SELECT RECORD_SOURCE_ID, SD_REAL_TIME_STATUS, COUNT(*)
FROM   SHORTWINDOW
WHERE  DD_PARTITION_DATE >= TRUNC(SYSDATE)-1
GROUP  BY RECORD_SOURCE_ID, SD_REAL_TIME_STATUS;

-- 1c. Same check on DETAIL (Manual Dialer 210 reads DETAIL, not SHORTWINDOW)
SELECT RECORD_SOURCE_ID,
       SD_REAL_TIME_DISPOSITION,
       SD_REAL_TIME_RULE_DISPOSITION,
       COUNT(*) AS CNT
FROM   DETAIL
WHERE  DD_PARTITION_DATE = TRUNC(SYSDATE)
GROUP  BY RECORD_SOURCE_ID, SD_REAL_TIME_DISPOSITION, SD_REAL_TIME_RULE_DISPOSITION
ORDER  BY RECORD_SOURCE_ID, CNT DESC;




-- 2a. Full add-in/auto-action inventory: every custom action type + its proc
SELECT LTYPE, NAME, AUTO_ACTION, AUTO_ACTION_PROC
FROM   ACTIONSTYPE
WHERE  AUTO_ACTION_PROC IS NOT NULL OR LTYPE >= 100
ORDER  BY LTYPE;

-- 2b. ACTIONSTEXT rows for the dialer action types — the exact rows the response procs
--     look up (LID/STEXT by LTYPE + action level + LSTATE/LSTATUS)
SELECT LTYPE, ACTION_LEVEL_ID, LID, LSTATE, LSTATUS, STEXT, REVIEW_SCREEN_TYPE
FROM   ACTIONSTEXT
WHERE  LTYPE IN (210, 215, 216, 217, 218, 219, 220, 221, 300, 310, 451, 452)
ORDER  BY LTYPE, ACTION_LEVEL_ID, LSTATE, LSTATUS;

-- 2c. Current ID high-water marks, so the new identifiers don't collide
SELECT MAX(LTYPE) AS MAX_ACTIONSTYPE_LTYPE FROM ACTIONSTYPE;
SELECT MAX(LID)   AS MAX_ACTIONSTEXT_LID   FROM ACTIONSTEXT;






-- 3a. Existing Sprinklr/dialer config params — confirms naming convention + current values
SELECT SCFGVARIABLE, SCFGVALUE, LCFGVALUE, LPORTFOLIOID
FROM   SYSTEMCONFIG
WHERE  UPPER(SCFGVARIABLE) LIKE '%DIALER%' OR UPPER(SCFGVARIABLE) LIKE '%SPKLR%'
ORDER  BY SCFGVARIABLE;

