     V_STRING_RULES	        VARCHAR2(500);
     V_SQL_STRNG			NVARCHAR2(4000);
     V_RULE_COUNT		    NUMBER(10,0);
     V_CHECK_RULE_COUNT		NUMBER(10,0):=0;
     V_AUTOACT_LACTID       NUMBER(10,0);
     V_AUTOACT_STEXT        NUMBER(10,0);
     V_AUTOACT_TYPE         NUMBER(10,0);
     V_ACTION_ORDER         NUMBER(10,0);
     V_RULE_ID              NUMBER(10,0);
     V_LREVID               NUMBER(10,0);
     V_MESSAGE_ID           NUMBER(10,0);
     V_IF_COUNT             NUMBER(10,0);
     V_VALID_RULES          VARCHAR2(200);
     V_DD_DATE              TIMESTAMP(3);
     V_STATE                NUMBER(10,0);
     V_STATUS               NUMBER(10,0);
     V_MASTER_DISP_CNT      NUMBER(10,0);
     V_DIALER_ACTION_TYPE_ID NUMBER := 451;

BEGIN
     SAVEPOINT NBMB_DACLR1;
     
     BEGIN
          SELECT IS_ENABLED INTO V_DYNAMIC_ENABLED FROM DYNAMIC_CSM_CONFIG 
          WHERE CSM_ID = V_DIALER_ACTION_TYPE_ID 
          AND ACTION_LEVEL_ID = p_ACTION_LEVEL_ID AND ROWNUM = 1;
     EXCEPTION
          WHEN NO_DATA_FOUND THEN NULL;
     END;

     IF (V_DYNAMIC_ENABLED = 1)
     THEN --1.3
          BEGIN
               SELECT NVL(AUTO_DIALER_FLAG,0) INTO V_IF_COUNT FROM TT_AUTO_DIALER_FLAG_EMPLOYEE  
               WHERE SD_TIEBREAKER = p_SD_TIEBREAKER AND ACTION_LEVEL_ID = p_ACTION_LEVEL_ID;  
          EXCEPTION
               WHEN NO_DATA_FOUND THEN NULL;
          END;

          IF (NVL(V_IF_COUNT,0)=1) 
          THEN --1.2
               BEGIN
                    SELECT ACTION_ORDER,RULE_ID
                    INTO V_ACTION_ORDER,V_RULE_ID
                    FROM TT_DIALER_CRITERIA_FLAG_EMPLOYEE 
                    WHERE  ACTION_LEVEL_KEY=p_ACTION_LEVEL_KEY
                    AND SD_TIEBREAKER=p_SD_TIEBREAKER
                    AND FLAG='N' AND ROWNUM = 1; --- check whether request should not sent
               EXCEPTION
                    WHEN NO_DATA_FOUND THEN NULL;
               END;

               IF V_ACTION_ORDER = 0 
               THEN
                    BEGIN
                         SELECT A.LREVID,B.LTYPE,B.LID,B.STEXT
                         INTO V_LREVID,V_AUTOACT_TYPE,V_AUTOACT_LACTID,V_AUTOACT_STEXT
                         FROM AUTOACTIONSRULE A
                         INNER JOIN ACTIONSTEXT B 
                         ON B.ACTION_LEVEL_ID=P_ACTION_LEVEL_ID AND  A.LACTIONID=B.LTYPE ---Generic Csm
                         AND B.LSTATE=1 AND B.LSTATUS=2 AND B.LTYPE=0  
                         WHERE A.LRULEID=V_RULE_ID AND LACTIONID <> V_DIALER_ACTION_TYPE_ID AND ROWNUM =1;
                    EXCEPTION
                         WHEN NO_DATA_FOUND THEN NULL;
                    END;

                    IF (( CAST(V_AUTOACT_LACTID AS VARCHAR2) IS NOT NULL ) AND  
                    ( CAST(V_AUTOACT_TYPE AS VARCHAR2) IS NOT NULL ) AND   
                    ( CAST(V_AUTOACT_STEXT AS VARCHAR2) IS NOT NULL ))   
                    THEN
                         ---- changes started to handle pre dial followed by post dialer block update issue ----- ADDED BY VAIBHAV ON 05APRIL2024
                         BEGIN
                             SELECT COUNT(1) INTO V_MASTER_DISP_CNT FROM TT_MASTERDISP_EMPLOYEE_DIALER_BLOCK_STATUS
                             WHERE ACTION_LEVEL_KEY = p_ACTION_LEVEL_KEY  AND SD_TIEBREAKER = p_SD_TIEBREAKER ;
                              
                             IF (V_MASTER_DISP_CNT > 0)
                             THEN
                                  SELECT STATE,STATUS INTO V_STATE,V_STATUS FROM TT_MASTERDISP_EMPLOYEE_DIALER_BLOCK_STATUS
                                  WHERE ACTION_LEVEL_KEY = p_ACTION_LEVEL_KEY AND SD_TIEBREAKER = p_SD_TIEBREAKER ;
                             
                                  IF ((V_STATE = 1) AND (V_STATUS = 0))
                                  THEN                    
                                       UPDATE MASTERDISP -----TO AVOID UNBLOCKING OF CARD ----- ADDED BY VAIBHAV ON 05APRIL2024
                                       SET STATE  = 1, STATUS = 0
                                       WHERE ACTION_LEVEL_ID	= P_ACTION_LEVEL_ID ---Generic Csm				   
                                       AND   ACTION_LEVEL_KEY	= p_ACTION_LEVEL_KEY
                                       AND   ACTIONID			= 0	;
                                  ELSE 
                                       UPDATE MASTERDISP -----TO AVOID DISFUNCTIONED BLOCK BUTTON----- ADDED BY JAHIR ON 20180131
                                       SET STATE  = 0,STATUS = 0
                                       WHERE ACTION_LEVEL_ID	= P_ACTION_LEVEL_ID ---Generic Csm				   
                                       AND   ACTION_LEVEL_KEY	= p_ACTION_LEVEL_KEY
                                       AND   ACTIONID			= 0	;
                                  END IF;
                             ELSE 
                                  UPDATE MASTERDISP -----TO AVOID DISFUNCTIONED BLOCK BUTTON----- ADDED BY JAHIR ON 20180131
                                  SET STATE  = 0, STATUS = 0
                                  WHERE ACTION_LEVEL_ID	= P_ACTION_LEVEL_ID ---Generic Csm				   
                                  AND   ACTION_LEVEL_KEY	= p_ACTION_LEVEL_KEY
                                  AND   ACTIONID			= 0	;
                             END IF;
                         EXCEPTION
                              WHEN NO_DATA_FOUND THEN NULL;
                         END;
---- changes ended to handle pre dial followed by post dialer block update issue -----
                    END IF;
               END IF;
               BEGIN
                    SELECT SD_RULES INTO V_STRING_RULES FROM DETAIL_ALERTED_RULE 
                    WHERE DD_PARTITION_DATE= p_DD_PARTITION_DATE 
                    AND ND_KEY_HASH       = 0
                    AND RECORD_SOURCE_ID  = 32
                    AND SD_TIEBREAKER	  = p_SD_TIEBREAKER 
                    AND ACTION_LEVEL_ID   = P_ACTION_LEVEL_ID---Generic Csm
                    AND ACTION_LEVEL_KEY  = p_ACTION_LEVEL_KEY;--INDEX COL DD_PARTITION_DATE, ND_KEY_HASH, RECORD_SOURCE_ID, SD_TIEBREAKER, ACTION_LEVEL_ID
               
               EXCEPTION 
                    WHEN NO_DATA_FOUND THEN NULL;
               END;
     
               V_VALID_RULES := CASE WHEN V_STRING_RULES IS NOT NULL THEN V_STRING_RULES ELSE NULL END;
               
               V_VALID_RULES := REPLACE(SUBSTR(V_VALID_RULES,2,LENGTH(V_VALID_RULES)-2),'.',',') ;
               V_RULE_COUNT := (LENGTH(V_VALID_RULES)-LENGTH(REPLACE(V_VALID_RULES,',','')))+1 ;
               
               V_SQL_STRNG := 'SELECT COUNT(DISTINCT(LRULEID)) FROM AUTOACTIONSRULE WHERE LRULEID IN ( ' || V_VALID_RULES || ' )';
     
               BEGIN -- checking all the rules are autoaction then only alert wiil get hold
                    EXECUTE IMMEDIATE V_SQL_STRNG INTO V_CHECK_RULE_COUNT; 
               
               EXCEPTION
                    WHEN OTHERS THEN 
                    V_MESSAGE := substr(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE||' SQLERRM: '||SQLERRM, 1, 2000);
                    PP_MAKE_AUDIT_ENTRY ('- Fetching Rule count -'|| V_MESSAGE,11,59);
               END;
               ---- other wise will update as rule criteria failed
     
               IF V_CHECK_RULE_COUNT <> V_RULE_COUNT 
               THEN  ----1.1 checking all the rules are autoaction then only alert wiil get hold
               ---- other wise will update as rule criteria failed
                    BEGIN
                         SELECT MESSAGE_ID,DD_DATE INTO V_MESSAGE_ID ,V_DD_DATE FROM 
                         EXTERNAL_MESSAGE_DATA
                         WHERE ACTION_LEVEL_KEY=p_ACTION_LEVEL_KEY
                         AND ACTION_LEVEL_ID = P_ACTION_LEVEL_ID---Generic Csm
                         AND ACTION_TYPE_ID = V_DIALER_ACTION_TYPE_ID
                         AND SD_TIEBREAKER = p_SD_TIEBREAKER
                         AND LSTATUS=1 AND ROWNUM=1;
                    
                    EXCEPTION
                         WHEN NO_DATA_FOUND THEN NULL;        
                    END;       
          
                    IF REGEXP_LIKE(V_MESSAGE_ID, '^[[:digit:]]+$') 
                    THEN 
                         UPDATE  EXTERNAL_MESSAGE_DATA 
                         SET LSTATUS     = 2,
                         DTCOMPLETED	= SYSTIMESTAMP,
                         SNOTE		= SNOTE ||'[**DIALER CRITERIA-FAILED**]'  ---- checking all the rules are autoaction then only alert wiil get hold
                         WHERE MESSAGE_ID = V_MESSAGE_ID;	                      ---- other wise will update as rule criteria failed
                    
                         DELETE FROM TT_DIALER_CRITERIA_FLAG_EMPLOYEE 
                         WHERE  ACTION_LEVEL_KEY=p_ACTION_LEVEL_KEY
                         AND SD_TIEBREAKER=p_SD_TIEBREAKER
                         AND FLAG='N';
                    END IF;
          
                    IF V_ACTION_ORDER = 0 
                    THEN --- Avoid post dialer button disfunction
                         BEGIN   
                              SELECT A.LREVID,B.LTYPE,B.LID,B.STEXT
                              INTO V_LREVID,V_AUTOACT_TYPE,V_AUTOACT_LACTID, V_AUTOACT_STEXT
                              FROM AUTOACTIONSRULE A  
                              INNER JOIN ACTIONSTEXT B 
                              ON B.ACTION_LEVEL_ID = P_ACTION_LEVEL_ID AND  A.LACTIONID=B.LTYPE ---Generic Csm
                              AND B.LSTATE=1 AND B.LSTATUS=2 AND B.LTYPE=0  
                              WHERE A.LRULEID=V_RULE_ID AND LACTIONID <> V_DIALER_ACTION_TYPE_ID AND ROWNUM = 1;
                         EXCEPTION
                              WHEN NO_DATA_FOUND THEN NULL;        
                         END; 
          
                         IF ( ( CAST(V_AUTOACT_LACTID AS VARCHAR2) IS NOT NULL ) AND  
                         (CAST(V_AUTOACT_TYPE AS VARCHAR2) IS NOT NULL ) AND   
                         ( CAST(V_AUTOACT_STEXT AS VARCHAR2) IS NOT NULL ))   
                         THEN
                              INSERT INTO ACT (ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY, NREVID,
                              LACTIONTYPE,  LACTIONID, LSTATE, LSTATUS, SACTACTION,
                              SACTNOTES, SACTNOTES2, SREASON_CODE)
                              VALUES
                              (p_ACTION_LEVEL_KEY, P_ACTION_LEVEL_ID,SYSTIMESTAMP,REPLACE(TO_CHAR(V_DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','') , V_LREVID,
                              V_AUTOACT_TYPE, V_AUTOACT_LACTID, 1, 2, V_AUTOACT_STEXT,
                              'Failed due to Dialer Rule CRITERIA-FAILED', NULL, NULL);
                         END IF;
                    END IF;
               ELSE ---1.1 if all rules are autoaction rules holding the alerts will release after dailer response or request failt condition
                    ---if all rules are autoaction rules
                    INSERT INTO TT_AUTO_DIALER_ADD_IN_ALERTS_EMPLOYEE 
                    (
                    ACTION_LEVEL_KEY,DD_PARTITION_DATE,ND_KEY_HASH,RECORD_SOURCE_ID,SD_TIEBREAKER,ACTION_LEVEL_ID,LRQAID,DD_DATE,ALERT_CATEGORY_ID,
                    LPORTFOLIOID,MD_TRAN_AMT1,DD_TRAN_DAT_TIM,ND_NEAR_TIME_SCORE,MM_OPEN_TO_BUY,MM_ACCT_AVAIL_BAL,SD_CASH_IND,SD_PIN_IND,
                    EMAIL_NOTIFICATION_IND,EMAIL_AFTER_TIME,REVIEWER_ID,ALERT_DATE
                    )
                    SELECT 
                    ACTION_LEVEL_KEY,DD_PARTITION_DATE,ND_KEY_HASH,RECORD_SOURCE_ID,SD_TIEBREAKER,ACTION_LEVEL_ID,LRQAID,DD_DATE,ALERT_CATEGORY_ID,
                    LPORTFOLIOID,MD_TRAN_AMT1,DD_TRAN_DAT_TIM,ND_NEAR_TIME_SCORE,MM_OPEN_TO_BUY,MM_ACCT_AVAIL_BAL,SD_CASH_IND,SD_PIN_IND,
                    EMAIL_NOTIFICATION_IND,EMAIL_AFTER_TIME,REVIEWER_ID,ALERT_DATE 
                    FROM ALERTS 
                    WHERE ACTION_LEVEL_KEY	=	p_ACTION_LEVEL_KEY 
                    AND ACTION_LEVEL_ID	= p_action_level_ID---Generic Csm
                    AND DD_PARTITION_DATE	=	p_DD_PARTITION_DATE
                    AND SD_TIEBREAKER		=	p_SD_TIEBREAKER;
                    
                    DELETE FROM ALERTS 	
                    WHERE ACTION_LEVEL_KEY	=	p_ACTION_LEVEL_KEY 
                    AND ACTION_LEVEL_ID	=   p_action_level_ID ---Generic Csm 
                    AND DD_PARTITION_DATE	=	p_DD_PARTITION_DATE 
                    AND SD_TIEBREAKER		=	p_SD_TIEBREAKER	;
                    
                    UPDATE TT_DIALER_CRITERIA_FLAG_EMPLOYEE 
                    SET FLAG='Y'
                    WHERE  ACTION_LEVEL_KEY=p_ACTION_LEVEL_KEY
                    AND SD_TIEBREAKER=p_SD_TIEBREAKER
                    AND FLAG='N';
                    
               END IF;--1.1
          END	IF; --1.2
     END IF; --1.3

     --** ADDED BY PRITAM ON 29/08/22
     DELETE FROM TT_AUTO_DIALER_FLAG_EMPLOYEE WHERE SD_TIEBREAKER = p_SD_TIEBREAKER AND ACTION_LEVEL_ID = p_ACTION_LEVEL_ID;
     
     DELETE FROM TT_MASTERDISP_EMPLOYEE_DIALER_BLOCK_STATUS
     WHERE ACTION_LEVEL_KEY = p_ACTION_LEVEL_KEY  AND SD_TIEBREAKER = p_SD_TIEBREAKER ; -- Deleting the Old state and status of incoming txn from tt table.
   
EXCEPTION
    WHEN OTHERS THEN
    ROLLBACK TO SAVEPOINT NBMB_DACLR1;---rollback;
    V_MESSAGE := SUBSTR(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE||' SQLERRM: '||SQLERRM, 1, 2000);
    PP_MAKE_AUDIT_ENTRY ( V_MESSAGE,11,59); 
        
    COMMIT;
END;
