create or replace PROCEDURE USP_QUEUE_PENDING_DIALER_ALERTS_SPRINKLR
AS
  V_MESSAGE NVARCHAR2(2000);
  V_COUNT NUMBER(10);
  V_AUTO_DIALER_ENABLED NUMBER(1);
  V_QUEUING_JOB_STATUS NUMBER(10); -- TO HOLD SPRINKLR CAMPAIGN WAITTIME NOT USED
BEGIN
  --  SELECT COUNT(1) INTO V_QUEUING_JOB_STATUS FROM ALL_SCHEDULER_RUNNING_JOBS WHERE UPPER(JOB_NAME) = 'DIALER_QUEUE_PENDING_ALERTS_SPRINKLR';

    EXECUTE IMMEDIATE 'TRUNCATE TABLE EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR';                

    INSERT  INTO EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR
	(SELECT /*+ parallel(3) */ MESSAGE_ID , ACTION_LEVEL_ID , LPORTFOLIOID , ACTION_TYPE_ID , ACTION_LEVEL_KEY , LSTATE , LSTATUS , DD_PARTITION_DATE ,
	SD_TIEBREAKER , DD_DATE , DTREQUESTED , DTSUBMITTED ,DTCOMPLETED , DTMOSTRECENTTXN , LREVID , SNOTE , LERRID,PRCSID,TRACKING_ID
	FROM EXTERNAL_MESSAGE_DATA PEMD
	WHERE PEMD.LPORTFOLIOID IN (SELECT LID FROM PORTFOLIOS PL WHERE PEMD.LPORTFOLIOID = PL.LID AND PL.ACTION_LEVEL_ID=PEMD.ACTION_LEVEL_ID AND ROWNUM =1)
--    EXISTS(SELECT 1 FROM PORTFOLIOS PL WHERE PEMD.LPORTFOLIOID = PL.LID AND PL.ACTION_LEVEL_ID=PEMD.ACTION_LEVEL_ID and rownum =1)  ---Generic Csm
	AND PEMD.ACTION_TYPE_ID in ( 215,216,217,218,219,220,221,210)
	AND ( PEMD.LSTATUS IN (1,3,88) OR PEMD.LERRID  IN ( 2,3 ) )
     AND PRCSID='S'); ---fetching pending Sprinklr dialer request


    DELETE FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR EMD_SP
    WHERE  ACTION_TYPE_ID in ( 215,216,217,218,219,220,221,210) AND LSTATUS IN (1,3,88) AND    
    DTREQUESTED >SYSTIMESTAMP - (SELECT TRACKING_ID/86400 FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR EMD_SP1 
    WHERE EMD_SP.MESSAGE_ID = EMD_SP1.MESSAGE_ID); -- Considered tracking_id/campaign_wait_time for first response sprinklr
    ---checking dailer request wait time less than and deleting those records from temtable as those will not be considered for late resp

    DELETE FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR   
    WHERE  ACTION_TYPE_ID in ( 215,216,217,218,219,220,221,210) AND LERRID IN (2,3)  AND    
    DTCOMPLETED >SYSTIMESTAMP - (SELECT LCFGVALUE/86400 FROM SYSTEMCONFIG  WHERE  SCFGVARIABLE='DIALER_WAIT_TIME_SECR_RESP'); 
    ---- fetching second response dialer wait time                                           

    SELECT COUNT(1)  INTO V_COUNT FROM  EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR WHERE ROWNUM = 1 ;

    IF (V_COUNT>0) THEN

        INSERT INTO ALERTS(
		ACTION_LEVEL_KEY, DD_PARTITION_DATE,ND_KEY_HASH,RECORD_SOURCE_ID,SD_TIEBREAKER,ACTION_LEVEL_ID,
		LRQAID,DD_DATE,ALERT_CATEGORY_ID,LPORTFOLIOID,MD_TRAN_AMT1,DD_TRAN_DAT_TIM,ND_NEAR_TIME_SCORE,
		MM_OPEN_TO_BUY,MM_ACCT_AVAIL_BAL,SD_CASH_IND,SD_PIN_IND,EMAIL_NOTIFICATION_IND,EMAIL_AFTER_TIME,REVIEWER_ID,ALERT_DATE)
        (SELECT A.ACTION_LEVEL_KEY,A.DD_PARTITION_DATE,A.ND_KEY_HASH,A.RECORD_SOURCE_ID,A.SD_TIEBREAKER,A.ACTION_LEVEL_ID,  
		A.LRQAID,A.DD_DATE,A.ALERT_CATEGORY_ID,A.LPORTFOLIOID,A.MD_TRAN_AMT1,A.DD_TRAN_DAT_TIM,A.ND_NEAR_TIME_SCORE,  
		A.MM_OPEN_TO_BUY,A.MM_ACCT_AVAIL_BAL,A.SD_CASH_IND,A.SD_PIN_IND,A.EMAIL_NOTIFICATION_IND,A.EMAIL_AFTER_TIME, A.REVIEWER_ID,ALERT_DATE 
        FROM TT_AUTO_DIALER_ADD_IN_ALERTS A JOIN EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR B
        ON ( A.SD_TIEBREAKER     = B.SD_TIEBREAKER )
        AND EXISTS (SELECT 1 FROM PORTFOLIOS PL WHERE B.LPORTFOLIOID  = PL.LID AND PL.ACTION_LEVEL_ID = B.ACTION_LEVEL_ID AND ROWNUM = 1)
        AND B.ACTION_TYPE_ID  in ( 215,216,217,218,219,220,221) ); 
             --AND B.LSTATUS =3

        DELETE FROM  TT_AUTO_DIALER_ADD_IN_ALERTS A
        WHERE ROWID IN(SELECT A.ROWID FROM TT_AUTO_DIALER_ADD_IN_ALERTS A JOIN EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR B
		ON (A.SD_TIEBREAKER     = B.SD_TIEBREAKER )
		AND EXISTS(SELECT 1 FROM PORTFOLIOS PL WHERE B.LPORTFOLIOID  = PL.LID AND PL.ACTION_LEVEL_ID = B.ACTION_LEVEL_ID AND ROWNUM = 1)
		AND B.ACTION_TYPE_ID in ( 215,216,217,218,219,220,221) );

        --------UPDATE   
        MERGE INTO EXTERNAL_MESSAGE_DATA A ---,INDEX(EXTERNAL_MESSAGE_DATA_PK))
        USING   EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR B 
        ON( A.MESSAGE_ID = B.MESSAGE_ID)  
        WHEN MATCHED THEN
        UPDATE SET A.LSTATUS = 96, A.LERRID = 96, A.SNOTE = SUBSTR(A.SNOTE || '-NO RESP,QUEUED TO ANALYST', 1, 255);

        -------insert into act table with response-------------------------------
        --INSERT INTO ACT FOR NO RESPONSE
        INSERT INTO ACT
        ( ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY, NREVID,LACTIONTYPE, LACTIONID, LSTATE, LSTATUS, SACTACTION,
        SACTNOTES, SACTNOTES2, SREASON_CODE )
        (SELECT A.ACTION_LEVEL_KEY ,A.ACTION_LEVEL_ID , SYSTIMESTAMP,REPLACE(TO_CHAR(DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','') , A.LREVID , A.ACTION_TYPE_ID ,B.LID,B.LSTATE, B.LSTATUS, B.STEXT,
        SUBSTR(A.SNOTE || '-NO RESP,QUEUED TO ANALYST', 1, 255), NULL, NULL 
        FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR A 
        INNER JOIN ACTIONSTEXT B ON B.REVIEW_SCREEN_TYPE=0 AND A.ACTION_LEVEL_ID=B.ACTION_LEVEL_ID AND 
        A.ACTION_TYPE_ID=B.LTYPE AND B.LSTATE=1 AND B.LSTATUS=2
        WHERE A.ACTION_TYPE_ID  in ( 215,216,217,218,219,220,221,210) AND A.LSTATUS  = 3 );---update as no response

        --INSERT INTO ACT FOR NO SECOND RESPONSE
        INSERT INTO ACT
        ( ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY,  NREVID, LACTIONTYPE, LACTIONID, LSTATE, LSTATUS,SACTACTION,
        SACTNOTES, SACTNOTES2, SREASON_CODE)
        (SELECT A.ACTION_LEVEL_KEY , A.ACTION_LEVEL_ID , SYSTIMESTAMP,REPLACE(TO_CHAR(DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','')  , A.LREVID , A.ACTION_TYPE_ID ,B.LID,B.LSTATE, B.LSTATUS, B.STEXT,
        SUBSTR(A.SNOTE ||'-NO SECOND RESP,QUEUED TO ANALYST', 1, 255) ,
        NULL , NULL FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR A
        INNER JOIN ACTIONSTEXT B ON B.REVIEW_SCREEN_TYPE=0 AND A.ACTION_LEVEL_ID=B.ACTION_LEVEL_ID AND 
        A.ACTION_TYPE_ID=B.LTYPE AND B.LSTATE=1 AND B.LSTATUS=2
        WHERE A.ACTION_TYPE_ID  IN ( 215,216,217,218,219,220,221,210) AND A.LERRID IN ( 2,3 ) );---update no second resp

        BEGIN
            SELECT LCFGVALUE INTO V_AUTO_DIALER_ENABLED FROM SYSTEMCONFIG WHERE  SCFGVARIABLE = 'DIALER_SPKLR_ENABLED';  

            EXCEPTION
              WHEN NO_DATA_FOUND THEN NULL;
        END;

        IF V_AUTO_DIALER_ENABLED = 1 THEN
            --INSERT INTO ACT FOR NO PULLING BY BATCH BECAUSE FLAG DISABLED
            INSERT INTO ACT
            ( ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY, NREVID,LACTIONTYPE, LACTIONID, LSTATE, LSTATUS, SACTACTION,
            SACTNOTES, SACTNOTES2, SREASON_CODE )
            (SELECT A.ACTION_LEVEL_KEY ,A.ACTION_LEVEL_ID , SYSTIMESTAMP,REPLACE(TO_CHAR(DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','') , A.LREVID , A.ACTION_TYPE_ID ,B.LID,B.LSTATE, B.LSTATUS, B.STEXT,
            SUBSTR(A.SNOTE || '-DELAY IN PULLING,QUEUED TO ANALYST', 1, 255) ,
            NULL , NULL FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR A 
            INNER JOIN ACTIONSTEXT B ON B.REVIEW_SCREEN_TYPE=0 AND A.ACTION_LEVEL_ID=B.ACTION_LEVEL_ID AND 
            A.ACTION_TYPE_ID=B.LTYPE AND B.LSTATE=1 AND B.LSTATUS=2
            WHERE A.ACTION_TYPE_ID  IN ( 215,216,217,218,219,220,221) AND A.LSTATUS  = 1 );
        ELSE
            --INSERT INTO ACT FOR NO PULLING BY BATCH BECAUSE FLAG DISABLED
            INSERT INTO ACT
            ( ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY, NREVID,LACTIONTYPE, LACTIONID, LSTATE, LSTATUS, SACTACTION,
            SACTNOTES, SACTNOTES2, SREASON_CODE )
            (SELECT A.ACTION_LEVEL_KEY ,A.ACTION_LEVEL_ID , SYSTIMESTAMP,REPLACE(TO_CHAR(DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','') , A.LREVID , A.ACTION_TYPE_ID ,B.LID,B.LSTATE, B.LSTATUS, B.STEXT,
            SUBSTR(A.SNOTE || '-BATCH PULLING FLAG DISABLED,QUEUED TO ANALYST', 1, 255) ,
            NULL , NULL FROM EMD_FOR_UPDATE_PENDING_RECORDS_SPRINKLR A 
            INNER JOIN ACTIONSTEXT B ON B.REVIEW_SCREEN_TYPE=0 AND A.ACTION_LEVEL_ID=B.ACTION_LEVEL_ID AND 
            A.ACTION_TYPE_ID=B.LTYPE AND B.LSTATE=1 AND B.LSTATUS=2
            WHERE A.ACTION_TYPE_ID  IN ( 215,216,217,218,219,220,221) AND A.LSTATUS  = 1 );
        END IF;
    END IF;

    COMMIT;

    EXCEPTION
        WHEN OTHERS THEN
        ROLLBACK;
        V_MESSAGE := substr(DBMS_UTILITY.FORMAT_ERROR_BACKTRACE||' SQLERRM: '||SQLERRM, 1, 2000);
        PP_MAKE_AUDIT_ENTRY ( V_MESSAGE,11,59); 
        COMMIT;
  END;
  
  
  
  
  
  
  
  
  
  
  
  
  
create or replace PROCEDURE USP_DIALER_REQUEST_POLLING_SPRINKLR (CUR OUT SYS_REFCURSOR)
AS

V_BLOCK_TIMEOUT INTEGER;
V_IF_COUNT INTEGER;
v_action_level_id number(10,0);
V_CSM_ID INTEGER;
V_MASTER_TABLE_NAME  VARCHAR2(255);
V_MSTER_KEY_COLUMN_NAME VARCHAR2(255);
V_DETAIL_KEY_COLUMN_NAME VARCHAR2(255);
V_SELECT_STATEMENT LONG;
V_COMMON_STMT LONG;
V_COMPLETE_STMT LONG;
V_MANUAL_COMMON_STMT LONG;
V_MANUAL_COMPLETE_STMT LONG;
V_IF_COUNT1 INTEGER;
V_MESSAGE    VARCHAR2(4000);
V_STARTBATCH INTEGER;
V_CHECK_BATCH INTEGER;
V_BATCH_COUNT INTEGER;
V_ERROR_STARTBATCH INTEGER; 
V_ERROR_CHECK_BATCH INTEGER;
V_SPRINKLR_ISENABLED NUMBER(1);
V_MESSAGE1    VARCHAR2(4000);
V_MESSAGE2    VARCHAR2(4000);
V_MESSAGE3    VARCHAR2(4000);

CURSOR DIALER_POLLING 
      IS
    SELECT ACTION_LEVEL_ID,CSM_ID,MASTER_TABLE_NAME,MASTER_KEY_COLUMN_NAME,DETAIL_KEY_COLUMN_NAME,CSM_SELECT_COLUMN
    from dynamic_csm_config where CSM_ID IN (210,215,216,217,218,219,220,221)  
    AND IS_ENABLED=1 ORDER BY ACTION_LEVEL_ID;

BEGIN

    BEGIN
        SELECT LCFGVALUE INTO V_BLOCK_TIMEOUT FROM SYSTEMCONFIG WHERE  UPPER(SCFGVARIABLE)='DIALERBLOCKTIMEOUT' ;
        EXCEPTION
        WHEN NO_DATA_FOUND THEN NULL;
    END;

    BEGIN  
        SELECT LCFGVALUE INTO V_BATCH_COUNT FROM SYSTEMCONFIG WHERE UPPER(SCFGVARIABLE)='DIALER_SPKLR_ROWNUM'; 
        EXCEPTION
        WHEN NO_DATA_FOUND THEN NULL;
    END;

    BEGIN  
        SELECT LCFGVALUE INTO V_SPRINKLR_ISENABLED FROM SYSTEMCONFIG WHERE UPPER(SCFGVARIABLE)='DIALER_SPKLR_ENABLED'; 
        EXCEPTION
        WHEN NO_DATA_FOUND THEN V_SPRINKLR_ISENABLED:=0;
    END;

    IF (V_SPRINKLR_ISENABLED = 1) THEN --Check if sprinklr enabled in systemconfig

    /*Inserting Failed/Timedout block requests into temp table*/
    INSERT INTO TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS 
    SELECT /*+ parallel(3) */ EMD.MESSAGE_ID,EMD.ACTION_TYPE_ID,EMD.DD_PARTITION_DATE,EMD.LPORTFOLIOID,EMD.ND_KEY_HASH,EMD.ND_RECORD_SOURCE_ID,
    EMD.LSTATUS,EMD.SD_TIEBREAKER,EMD.ACTION_LEVEL_ID,EMD.ACTION_LEVEL_KEY,EMD.LREVID,EMD.SNOTE,
    CASE WHEN BEMD.LSTATUS= 2 THEN 'F' ELSE 'T' END AS FLAG,BEMD.LSTATUS AS BLOCK_LSTATUS,EMD.PRCSID,EMD.DD_DATE
    FROM EXTERNAL_MESSAGE_DATA EMD  
    INNER JOIN EXTERNAL_MESSAGE_DATA BEMD 
    ON EXISTS (SELECT 1 FROM PORTFOLIOS PL WHERE 
                              PL.ACTION_LEVEL_ID IN (1,2,3,4,5,6,7) AND  ----generic csm
                              EMD.LPORTFOLIOID=PL.LID
                             AND ROWNUM=1 )
     AND EMD.ACTION_TYPE_ID IN(215,216,217,218,219,220,221)
     AND EMD.LSTATUS = 1
     AND EMD.PRCSID = 'S'  --added to match only sprinklr requests
     AND EMD.SNOTE2 = '1'
     AND EMD.ACTION_LEVEL_KEY =BEMD.ACTION_LEVEL_KEY  
     AND EMD.ACTION_LEVEL_ID = BEMD.ACTION_LEVEL_ID
     AND EMD.SD_TIEBREAKER=BEMD.SD_TIEBREAKER 
     AND EMD.LPORTFOLIOID = BEMD.LPORTFOLIOID
     AND BEMD.ACTION_TYPE_ID = 0
     AND (BEMD.LSTATUS = 2 OR
     (BEMD.LSTATUS IN (1,3) and BEMD.DTREQUESTED <=(CAST(SYSDATE AS TIMESTAMP)- V_BLOCK_TIMEOUT/86400))); ----Supressing block timeout and faild request to alert.
    /*Inserting Failed/Timedout block requests into temp table*/

    SELECT COUNT(1) INTO V_IF_COUNT FROM TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS
    WHERE PRCSID = 'S'  --added to match only sprinklr requests
    AND ROWNUM=1;

    /*Queued Failed/Timedout block requests to analysts and delete records from respective tables*/
    IF V_IF_COUNT > 0 THEN 
        INSERT INTO ALERTS
            (ACTION_LEVEL_KEY,DD_PARTITION_DATE  ,ND_KEY_HASH  ,RECORD_SOURCE_ID  ,
            SD_TIEBREAKER  ,ACTION_LEVEL_ID   ,LRQAID  ,DD_DATE  ,ALERT_CATEGORY_ID  ,LPORTFOLIOID   ,
            MD_TRAN_AMT1  ,DD_TRAN_DAT_TIM  ,ND_NEAR_TIME_SCORE ,MM_OPEN_TO_BUY  ,MM_ACCT_AVAIL_BAL  ,
            SD_CASH_IND  ,SD_PIN_IND  ,EMAIL_NOTIFICATION_IND  ,EMAIL_AFTER_TIME  ,REVIEWER_ID  ,ALERT_DATE ) 
        SELECT /*+ parallel(3) */ DA.ACTION_LEVEL_KEY,DA.DD_PARTITION_DATE  ,DA.ND_KEY_HASH  ,DA.RECORD_SOURCE_ID  ,
            DA.SD_TIEBREAKER  ,DA.ACTION_LEVEL_ID   ,DA.LRQAID  ,DA.DD_DATE  , DA.ALERT_CATEGORY_ID  ,DA.LPORTFOLIOID   ,
            DA.MD_TRAN_AMT1  ,DA.DD_TRAN_DAT_TIM  ,DA.ND_NEAR_TIME_SCORE ,DA.MM_OPEN_TO_BUY  ,DA.MM_ACCT_AVAIL_BAL  ,
            DA.SD_CASH_IND  ,DA.SD_PIN_IND  ,DA.EMAIL_NOTIFICATION_IND  ,DA.EMAIL_AFTER_TIME  ,DA.REVIEWER_ID  ,DA.ALERT_DATE 
        FROM TT_AUTO_DIALER_ADD_IN_ALERTS DA 
        INNER JOIN TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS EMD 
          ON  DA.SD_TIEBREAKER		= EMD.SD_TIEBREAKER 
              AND DA.LPORTFOLIOID = EMD.LPORTFOLIOID
              AND EMD.LSTATUS = 1
              AND EMD.PRCSID = 'S'  --added to match only sprinklr requests
              AND DA.DD_PARTITION_DATE	= EMD.DD_PARTITION_DATE 
              AND DA.ND_KEY_HASH        = EMD.ND_KEY_HASH 
              AND DA.RECORD_SOURCE_ID   = EMD.ND_RECORD_SOURCE_ID;     ----Inserting alerts failed 

        INSERT INTO ACT (ACTION_LEVEL_KEY, ACTION_LEVEL_ID, DTACTDATEKEY,TDDATEKEY, NREVID,
            LACTIONTYPE,  LACTIONID, LSTATE, LSTATUS, SACTACTION,
            SACTNOTES, SACTNOTES2, SREASON_CODE)	 
        SELECT A.ACTION_LEVEL_KEY,A.ACTION_LEVEL_ID, SYSTIMESTAMP,REPLACE(TO_CHAR(DD_DATE,'YYYY-MM-DD HH24:MI:SS.FF3'),'-','') ,A.LREVID, A.ACTION_TYPE_ID, B.LID,
            B.LSTATE, B.LSTATUS, B.STEXT,SNOTE ||(CASE WHEN FLAG = 'F' 
            THEN 'QUEUED TO ANALYST DUE TO BLOCK FAILED' ELSE 'QUEUED TO ANALYST DUE TO BLOCK PENDING' END),NULL, NULL
        FROM TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS A 
        INNER JOIN ACTIONSTEXT B ON B.REVIEW_SCREEN_TYPE=0 AND A.ACTION_LEVEL_ID=B.ACTION_LEVEL_ID AND 
        A.ACTION_TYPE_ID=B.LTYPE AND B.LSTATE=1 AND B.LSTATUS=2 
        WHERE A.PRCSID='S'; --added to match only sprinklr requests

        UPDATE EXTERNAL_MESSAGE_DATA A
        SET A.LSTATUS = 96,A.SNOTE=(SELECT (CASE WHEN B.FLAG = 'F'
        THEN '-QUEUED TO ANALYST DUE TO BLOCK FAILED' ELSE '-QUEUED TO ANALYST DUE TO BLOCK PENDING' END)  FROM 
        TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS B WHERE A.MESSAGE_ID=B.MESSAGE_ID ),A.DTCOMPLETED = SYSTIMESTAMP 
        WHERE EXISTS (SELECT 1 FROM TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS C 
                        WHERE A.MESSAGE_ID = C.MESSAGE_ID 
                        AND C.PRCSID='S') --added to match only sprinklr requests
                    AND A.PRCSID='S'; --added to match only sprinklr requests

        DELETE  FROM TT_AUTO_DIALER_ADD_IN_ALERTS TT
        WHERE  EXISTS (SELECT 1 FROM TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS FTR
                        WHERE TT.SD_TIEBREAKER     = FTR.SD_TIEBREAKER 
                        AND FTR.PRCSID='S' --added to match only sprinklr requests
                        AND ROWNUM=1);
--                    AND TT.PRCSID='S'; --added to match only sprinklr requests

        DELETE  FROM TT_DIALER_CRITERIA_FLAG A 
        WHERE EXISTS (SELECT 1 FROM TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS  B WHERE  --- Deleting record form criteria flag table
                        A.ACTION_LEVEL_KEY=B.ACTION_LEVEL_KEY AND A.SD_TIEBREAKER=B.SD_TIEBREAKER  
                         AND B.PRCSID='S' --added to match only sprinklr requests
                         AND ROWNUM =1)
                        AND A.PRCSID='S'; --added to match only sprinklr requests

        DELETE FROM  TT_AUTO_DIALER_FAILED_TIMEDOUT_REQUESTS
        WHERE PRCSID='S'; --added to match only sprinklr requests

    END IF;
    /*Queued Failed/Timedout block requests to analysts and delete records from respective tables*/

    DELETE FROM TT_DIALER_POLLING_REQUEST
    WHERE PRCSID='S'; --added to match only sprinklr requests

    DELETE FROM EMD_DIALER_REQUEST
    WHERE PRCSID='S'; --added to match only sprinklr requests

    INSERT INTO TT_DIALER_POLLING_REQUEST 
    SELECT /*+ parallel(3) */ MESSAGE_ID,ACTION_LEVEL_ID,LPORTFOLIOID,ACTION_TYPE_ID,ACTION_LEVEL_KEY,LSTATE,LSTATUS,
    DD_PARTITION_DATE,ND_KEY_HASH,ND_RECORD_SOURCE_ID,SD_TIEBREAKER,DD_DATE,TDDATEKEY,DTREQUESTED,
    DTSUBMITTED,DTCOMPLETED,DTMOSTRECENTTXN,DTENDDATE,LREVID,LERRID,SEMSG,SHOST_DATA,SREASON_CODE,SD_SEQ_NUM,
    SD_MBR_NUM,SM_FIID,SM_BIN,SNOTE,SNOTE2,SNOTIFYTYPE,RULE_ID,SD_MARK_SOURCE,RESPONSECODE,DTSTARTDATE,PRCSID,
    TRACKING_ID,'N' as PROCESSED_FLAG FROM external_message_data EMD
    WHERE  EXISTS (SELECT 1 FROM PORTFOLIOS PL WHERE EMD.ACTION_LEVEL_ID=PL.ACTION_LEVEL_ID AND ---Generic Csm
			  EMD.LPORTFOLIOID=PL.LID AND PL.NSTATUS = 1 AND ROWNUM=1)
			  --Condition added to return true when it is a predialer rule and the block has been succeeded 
			  --or it is a post dialer rule and dialer request is placed    
			  AND EMD.ACTION_TYPE_ID IN (215,216,217,218,219,220,221)
			  AND EMD.LSTATUS = 1 
              AND EMD.PRCSID = 'S' --added to match only sprinklr requests
			  AND (CASE WHEN EMD.SNOTE2 = '1'
			   THEN (CASE WHEN EXISTS (SELECT 1 FROM AUTOACTIONSRULE WHERE LRULEID = EMD.SHOST_DATA AND LACTIONID IN (3,5) AND ROWNUM=1)
			   THEN 0 WHEN EXISTS
			  (SELECT 1 FROM EXTERNAL_MESSAGE_DATA E 
			  WHERE EMD.LPORTFOLIOID = E.LPORTFOLIOID AND
			  E.ACTION_LEVEL_KEY = EMD.ACTION_LEVEL_KEY AND
			  E.ACTION_LEVEL_ID = EMD.ACTION_LEVEL_ID AND
			  E.ACTION_TYPE_ID = 0 AND
			  E.SD_TIEBREAKER = EMD.SD_TIEBREAKER AND  
              E.LSTATUS = 0 AND ROWNUM=1) THEN 0 END) ELSE 0 END) = 0
              UNION ALL
              SELECT /*+ parallel(3) */ MESSAGE_ID,ACTION_LEVEL_ID,LPORTFOLIOID,ACTION_TYPE_ID,ACTION_LEVEL_KEY,LSTATE,LSTATUS,
                DD_PARTITION_DATE,ND_KEY_HASH,ND_RECORD_SOURCE_ID,SD_TIEBREAKER,DD_DATE,TDDATEKEY,DTREQUESTED,
                DTSUBMITTED,DTCOMPLETED,DTMOSTRECENTTXN,DTENDDATE,LREVID,LERRID,SEMSG,SHOST_DATA,SREASON_CODE,SD_SEQ_NUM,
                SD_MBR_NUM,SM_FIID,SM_BIN,SNOTE,SNOTE2,SNOTIFYTYPE,RULE_ID,SD_MARK_SOURCE,RESPONSECODE,DTSTARTDATE,PRCSID,
                TRACKING_ID,'N' AS PROCESSED_FLAG FROM EXTERNAL_MESSAGE_DATA EMD
              WHERE EXISTS (SELECT 1 FROM PORTFOLIOS PL  WHERE EMD.ACTION_LEVEL_ID=PL.ACTION_LEVEL_ID AND EMD.LPORTFOLIOID=PL.LID  
                            AND PL.NSTATUS =1 AND ROWNUM=1 ) ---csm generic
              AND EMD.ACTION_TYPE_ID IN (210)  
              AND EMD.LSTATUS = 1
              AND EMD.PRCSID = 'S'; --added to match only sprinklr requests

    V_COMMON_STMT:= ' FROM SHORTWINDOW SW
    INNER JOIN TT_DIALER_POLLING_REQUEST_BATCH TT
    ON  SW.SD_TIEBREAKER	  = TT.SD_TIEBREAKER
    AND SW.DD_PARTITION_DATE  = TT.DD_PARTITION_DATE 
    AND SW.ND_KEY_HASH        = TT.ND_KEY_HASH 
    AND SW.RECORD_SOURCE_ID   = TT.ND_RECORD_SOURCE_ID ';

    V_MANUAL_COMMON_STMT:= ' FROM DETAIL D
      INNER JOIN TT_DIALER_POLLING_REQUEST_BATCH TT
      ON  D.SD_TIEBREAKER      = TT.SD_TIEBREAKER
      AND D.DD_PARTITION_DATE  = TT.DD_PARTITION_DATE
      AND D.ND_KEY_HASH        = TT.ND_KEY_HASH 
      AND D.RECORD_SOURCE_ID   = TT.ND_RECORD_SOURCE_ID ';

    OPEN DIALER_POLLING ;

    FETCH DIALER_POLLING INTO v_action_level_id,V_CSM_ID,V_MASTER_TABLE_NAME,V_MSTER_KEY_COLUMN_NAME,V_DETAIL_KEY_COLUMN_NAME,V_SELECT_STATEMENT;

    V_MASTER_TABLE_NAME := CASE WHEN V_MASTER_TABLE_NAME IS NOT NULL THEN V_MASTER_TABLE_NAME
                        ELSE NULL END;
    V_MSTER_KEY_COLUMN_NAME := CASE WHEN V_MSTER_KEY_COLUMN_NAME IS NOT NULL THEN V_MSTER_KEY_COLUMN_NAME
                        ELSE NULL END;
    V_DETAIL_KEY_COLUMN_NAME := CASE WHEN V_DETAIL_KEY_COLUMN_NAME IS NOT NULL THEN V_DETAIL_KEY_COLUMN_NAME
                        ELSE NULL END;  
    V_SELECT_STATEMENT := CASE WHEN V_SELECT_STATEMENT IS NOT NULL THEN V_SELECT_STATEMENT
                        ELSE NULL END; 

    WHILE (DIALER_POLLING%FOUND) LOOP --1.2 --MAIN WHILE LOOP START
    BEGIN --1.2 --MAIN WHILE BEGIN-END
        V_IF_COUNT1 := 0;

        SELECT COUNT(1) INTO V_IF_COUNT1 FROM TT_DIALER_POLLING_REQUEST WHERE ACTION_LEVEL_ID=v_action_level_id 
