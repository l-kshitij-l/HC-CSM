                SD_MARK_SOURCE = 'SECOND_REQ '
                WHERE LSTATUS IN (3,88);  

                INSERT INTO TT_AUTO_DIALER_ADD_IN_ALERTS 
                    (ACTION_LEVEL_KEY, 
                    DD_PARTITION_DATE, 
                    ND_KEY_HASH, 
                    RECORD_SOURCE_ID, ---if all rules are autoaction rules
                    SD_TIEBREAKER,
                    ACTION_LEVEL_ID, 
                    LRQAID, 
                    DD_DATE,
                    ALERT_CATEGORY_ID,
                    LPORTFOLIOID,
                    MD_TRAN_AMT1,
                    DD_TRAN_DAT_TIM,
                    ND_NEAR_TIME_SCORE,
                    MM_OPEN_TO_BUY, 
                    MM_ACCT_AVAIL_BAL, 
                    SD_CASH_IND, 
                    SD_PIN_IND,
                    EMAIL_NOTIFICATION_IND,
                    EMAIL_AFTER_TIME,
                    REVIEWER_ID, 
                    ALERT_DATE)
                SELECT
                    ACTION_LEVEL_KEY, 
                    DD_PARTITION_DATE, 
                    ND_KEY_HASH,
                    RECORD_SOURCE_ID, 
                    SD_TIEBREAKER, 
                    ACTION_LEVEL_ID,
                    LRQAID, DD_DATE, 
                    ALERT_CATEGORY_ID, 
                    LPORTFOLIOID, 
                    MD_TRAN_AMT1, 
                    DD_TRAN_DAT_TIM,
                    ND_NEAR_TIME_SCORE, 
