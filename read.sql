    SD_PRM_MESSAGE_TYP,SD_PROD_IND,SD_SEQ_NUM,SD_TRAN_CDE,MD_TRAN_AMT1,SD_MSG_TYP,SD_RESP_CDE,SD_PT_SRV_COND_CDE,SD_PT_SRV_ENTRY_MDE,       
    SD_EMV_USER_FILLER,SD_TRACK1_2_IND,SD_RETL_SIC_CDE,SD_TERM_NAME_LOC,SD_TERM_CITY,SD_TERM_ST,                  
    SD_TERM_CNTRY,SD_TERM_POSTAL_CDE,SD_MBR_NUM,SD_PIN_IND,SM_CUST_MSTR_FLD1,SM_USER_CNTRY,SM_USER_POSTAL_CDE,
    --SUBSTR(SM_SEC_FIRST_NAM,1,2)||RPAD('X' ,LENGTH(SM_SEC_FIRST_NAM)-4,'X')||REVERSE(SUBSTR(REVERSE(SM_SEC_FIRST_NAM),1,2)) SM_SEC_FIRST_NAM,
