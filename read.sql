    BEGIN   
        SELECT LCFGVALUE INTO V_LCFGVALUE FROM SYSTEMCONFIG  WHERE SCFGVARIABLE ='DIALER_SPKLR_PENDING_REQ_RETRY' AND ROWNUM = 1;
        EXCEPTION 
            WHEN NO_DATA_FOUND THEN V_LCFGVALUE:=0;
    END;

    BEGIN
        IF(V_LCFGVALUE = 1)THEN
            OPEN DIALER_PENDING_REQUEST; 
            LOOP
                FETCH DIALER_PENDING_REQUEST INTO V_ACTION_LEVEL_KEY, V_ACTION_LEVEL_ID, V_DD_PARTITION_DATE, V_SD_TIEBREAKER;

                EXIT WHEN DIALER_PENDING_REQUEST%NOTFOUND;  

