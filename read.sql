     AND DTREQUESTED > SYSTIMESTAMP - (SELECT LCFGVALUE/86400 FROM SYSTEMCONFIG WHERE UPPER(SCFGVARIABLE)='DIALER_SPKLR_PNDG_RETRY_TIME');

